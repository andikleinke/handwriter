/** The template for a glyph's text, or null for anything but a single letter. */
export function templateFor(chars) {
  const c = (chars || '').trim();
  return c.length === 1 && L[c] ? L[c] : null;
}

/**
 * How well an ordered pen path follows a template, 0..1.
 *
 * `path` is the whole pen path (strokes concatenated in order) in normalised
 * coordinates. Waypoints are aligned to path positions monotonically by
 * dynamic programming, so order and direction of travel both count; each
 * waypoint contributes 1 at zero distance falling to 0 at `radius`.
 */
export function templateFit(template, path, radius = 0.3) {
  const wps = template.flat();
  const K = wps.length, N = path.length;
  if (!K || N < 2) return 0;
  const INF = 1e9;
  // best[k][i] = min cost aligning waypoints 0..k with waypoint k at path[i]
  let prev = new Float64Array(N);
  for (let i = 0; i < N; i++) prev[i] = costAt(wps[0], path[i], radius);
  for (let k = 1; k < K; k++) {
    const cur = new Float64Array(N).fill(INF);
    let runMin = INF;
    for (let i = 0; i < N; i++) {
      if (i > 0 && prev[i - 1] < runMin) runMin = prev[i - 1];
      if (runMin < INF) cur[i] = runMin + costAt(wps[k], path[i], radius);
    }
    prev = cur;
  }
  let best = INF;
  for (let i = 0; i < N; i++) if (prev[i] < best) best = prev[i];
  if (best >= INF) return 0;
  return Math.max(0, 1 - best / K);
}

/** 0 when on the waypoint, 1 at `radius` and beyond. */
function costAt(w, p, radius) {
  const d = Math.hypot(p[0] - w[0], p[1] - w[1]);
  return Math.min(1, d / radius);
}
