/**
 * Letterform knowledge: how each Latin letter is written in cursive, as a
 * coarse ordered list of waypoints the pen passes through.
 *
 * Ink alone cannot say that an 'A' is written up the left leg, over the
 * apex and down the right leg — a brush font may well make the left leg the
 * heavy stroke. These templates supply the convention; the geometric score
 * still decides everything the template leaves open.
 *
 * Coordinates are normalised to the glyph's bounding box: x from 0 (left)
 * to 1 (right), y from 0 (bottom) to 1 (top). Each template is a list of
 * pen-down strokes, each a list of waypoints. Tolerances are generous —
 * these are meant to be matched by a dynamic-programming alignment, not hit.
 */

